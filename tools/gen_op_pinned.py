#!/usr/bin/env python3
"""Regenerate gvn/op_pinned_gen.mbt from vendor/qbe/ops.h.

The pinned column is the tenth flag of the F() macro in ops.h. Hand-copying it
drifted once already (blit0/blit1 were missing, so gvn deleted half of a blit),
so the list is generated instead: run this after updating vendor/qbe.
"""
import io, os, re, sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ops = io.open(os.path.join(root, 'vendor', 'qbe', 'ops.h'), encoding='utf-8').read()
opmbt = io.open(os.path.join(root, 'types', 'op.mbt'), encoding='utf-8').read()
variants = set(re.findall(r'^  ([A-Z][A-Za-z0-9]*)$', opmbt, re.M))

pinned, missing = [], []
for m in re.finditer(r'^O\(\s*([a-z0-9_]+),\s*T\([^)]*\),\s*F\(([^)]*)\)', ops, re.M):
    name = m.group(1)
    flags = [f.strip() for f in m.group(2).split(',')]
    if len(flags) < 10 or flags[9] != '1':
        continue
    v = name[0].upper() + name[1:]
    if v in variants:
        pinned.append(v)
    else:
        missing.append(name)

# ops this port has that upstream does not; they also have memory side effects
extras = ['Vacall', 'AtomicLoad', 'AtomicStore', 'Fence']
names = pinned + extras
arms = ['    | @types.' + v for v in names]
arms[0] = '    @types.' + names[0]
body = '///|' + chr(10)
body += '// Generated by tools/gen_op_pinned.py from vendor/qbe/ops.h.' + chr(10)
body += '// Do not edit by hand: the tenth F() flag is the pinned column.' + chr(10)
body += 'fn op_pinned_generated(i : @types.Ins) -> Bool {' + chr(10)
body += '  match i.op {' + chr(10)
body += (chr(10).join(arms)) + ' => true' + chr(10)
body += '    _ => false' + chr(10)
body += '  }' + chr(10)
body += '}' + chr(10)
io.open(os.path.join(root, 'gvn', 'op_pinned_gen.mbt'), 'w', encoding='utf-8').write(body)
print('pinned ops generated:', len(pinned) + len(extras))
if missing:
    print('not implemented in this port (skipped):', ' '.join(missing))